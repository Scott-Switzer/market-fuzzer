#: Identifier and version of the plan that reproduces the M10.6 campaign.
DEFAULT_PLAN_ID = "m10_6_open_ood_v1"
DEFAULT_PLAN_VERSION = "v1"

#: Machine-readable code an M10.7 export gate reports for withheld worlds.
SEALED_PLAN_EXPORT_ERROR = "SEALED_EVAL_NOT_TRAINABLE"

#: What a *public* result calls a campaign that contains sealed worlds. The real
#: plan identifier can itself name an evaluator-private study, so public output
#: reports the redaction while the replay package keeps the identifier.
SEALED_PLAN_LABEL = "evaluator-private plan"


class DatasetSplit(StrEnum):
    """What a world may be used for.

    M10.6.1 does not build training worlds yet, but the classification exists now
    so M10.7's corpus exporter cannot be written without confronting it: a sealed
    evaluation world is *never* trainable, however convenient it would be.
    """

    #: Generated explicitly for training and never used for official scoring.
    TRAINABLE = "trainable"
    #: An official evaluation world generated by a published process family.
    PUBLIC_EVAL = "public_eval"
    #: An official evaluation world generated by an evaluator-private family.
    SEALED_EVAL = "sealed_eval"


class SealedEvaluationExportError(RuntimeError):
    """An export asked to include a world that is not trainable."""

    code = SEALED_PLAN_EXPORT_ERROR

    def __init__(self, splits: tuple[DatasetSplit, ...]) -> None:
        offenders = ", ".join(sorted({split.value for split in splits}))
        super().__init__(
            f"{SEALED_PLAN_EXPORT_ERROR}: only TRAINABLE worlds may be exported, got {offenders}"
        )
        self.splits = splits


def is_trainable(split: DatasetSplit) -> bool:
    """Whether a world in ``split`` may be written into a training corpus."""

    return split is DatasetSplit.TRAINABLE


def require_trainable(splits: tuple[DatasetSplit, ...]) -> None:
    """The M10.7 export gate: raise unless every split is trainable.

    Declared here, with its tests, so the exporter that follows cannot quietly
    reach into an evaluation campaign for data.
    """

    if any(not is_trainable(split) for split in splits):
        raise SealedEvaluationExportError(tuple(splits))


@dataclass(frozen=True, slots=True)
class EvaluationWorldTemplate:
    """One entry of an evaluation plan: *what* a world is, before it is built."""

    partition: EvaluationPartition
    family_id: str
    ecology_id: str
    weight: int = 1

    def __post_init__(self) -> None:
        if self.weight < 1:
            raise ValueError("a template weight must be at least one")
        if not self.family_id:
            raise ValueError("a template needs a process family id")
        if not self.ecology_id:
            raise ValueError("a template needs an ecology id")


@dataclass(frozen=True, slots=True)
class EvaluationPlan:
    """An immutable, explicitly stated evaluation campaign.

    ``worlds`` is a cycle, not a complete list: a plan of six templates runs world
    ``i`` on template ``i % 6``, so the same plan describes a 12-world or a
    32-world campaign without being restated per world count.
    """

    plan_id: str
    version: str
    worlds: tuple[EvaluationWorldTemplate, ...]
    description: str = ""

    def __post_init__(self) -> None:
        if not self.plan_id or not self.version:
            raise ValueError("a plan needs an identifier and a version")
        if not self.worlds:
            raise ValueError("a plan needs at least one world template")

    def cycle(self) -> tuple[EvaluationWorldTemplate, ...]:
        """The template cycle with every weight expanded in place."""

        return tuple(template for template in self.worlds for _ in range(template.weight))

    def template_for(self, index: int) -> EvaluationWorldTemplate:
        """The template world ``index`` uses."""

        if index < 0:
            raise ValueError("a world index must be non-negative")
        cycle = self.cycle()
        return cycle[index % len(cycle)]

    def family_ids(self) -> tuple[str, ...]:
        """Every process family this plan names, sorted."""

        return tuple(sorted({template.family_id for template in self.worlds}))

    def ecology_ids(self) -> tuple[str, ...]:
        """Every ecology this plan names, sorted."""

        return tuple(sorted({template.ecology_id for template in self.worlds}))


@dataclass(frozen=True, slots=True)
class PlannedWorld:
    """One fully resolved world: identity, provenance, and split classification."""

    plan_id: str
    plan_version: str
    index: int
    world_id: str
    seed: int
    template: EvaluationWorldTemplate
    ecology: EcologyProfile
    family_visibility: FamilyVisibility
    public_family_label: str
    family_commitment: str
    split: DatasetSplit

    @property
    def partition(self) -> EvaluationPartition:
        return self.template.partition

    @property
    def family_id(self) -> str:
        """The real family id. Evaluator-private: never publish it unredacted."""

        return self.template.family_id

    @property
    def ecology_id(self) -> str:
        return self.ecology.label

    @property
    def sealed(self) -> bool:
        """Whether this world ran on an evaluator-private family."""

        return self.split is DatasetSplit.SEALED_EVAL

    @property
    def trainable(self) -> bool:
        return is_trainable(self.split)


class EcologyRegistry:
    """An explicit ``ecology id -> EcologyProfile`` registry.

    Ecologies are published with the benchmark (they describe the tradable
    environment, not the generator), so this registry is a lookup rather than a
    secrecy boundary. It exists so a plan can name an ecology instead of branching
    on a hard-coded label inside the runner.
    """

    def __init__(self) -> None:
        self._profiles: dict[str, EcologyProfile] = {}

    def register(self, profile: EcologyProfile) -> None:
        if profile.label in self._profiles:
            raise ValueError(f"ecology {profile.label!r} is already registered")
        self._profiles[profile.label] = profile

    def resolve(self, ecology_id: str) -> EcologyProfile:
        try:
            return self._profiles[str(ecology_id)]
        except KeyError as exc:
            raise KeyError(f"UNKNOWN_ECOLOGY: no ecology is registered as {ecology_id!r}") from exc

    def contains(self, ecology_id: str) -> bool:
        return str(ecology_id) in self._profiles

    def ecology_ids(self) -> tuple[str, ...]:
        return tuple(sorted(self._profiles))


def default_ecology_registry() -> EcologyRegistry:
    """A fresh registry holding the published ecologies."""

    registry = EcologyRegistry()
    for profile in (FAMILIAR_ECOLOGY, DISTRIBUTION_ECOLOGY):
        registry.register(profile)
    return registry


def default_evaluation_plan() -> EvaluationPlan:
    """``m10_6_open_ood_v1``: the M10.6 campaign, stated explicitly.

    The six-template cycle is the M10.6 assignment made explicit. World ``i`` of
    the M10.6 runner used ``i % 3`` for the partition and rotated the two held-out
    families by ``(i // 3) % 2``; over a six-world cycle that is exactly

        familiar, distribution, mechanism(stochastic-vol),
        familiar, distribution, mechanism(regime-jump)

    so the default plan reproduces the M10.6 world identities, seeds, partitions,
    and generators byte for byte.
    """

    return EvaluationPlan(
        plan_id=DEFAULT_PLAN_ID,
        version=DEFAULT_PLAN_VERSION,
        description="Open-source process-family OOD: baseline and shifted ecology, two published held-out families.",
        worlds=(
            EvaluationWorldTemplate(
                partition=EvaluationPartition.FAMILIAR,
                family_id=FAMILIAR_FAMILY_ID,
                ecology_id=FAMILIAR_ECOLOGY.label,
            ),
            EvaluationWorldTemplate(
                partition=EvaluationPartition.DISTRIBUTION,
                family_id=FAMILIAR_FAMILY_ID,
                ecology_id=DISTRIBUTION_ECOLOGY.label,
            ),
            EvaluationWorldTemplate(
                partition=EvaluationPartition.MECHANISM,
                family_id=STOCHASTIC_VOL_FACTOR_T_V1,
                ecology_id=DISTRIBUTION_ECOLOGY.label,
            ),
            EvaluationWorldTemplate(
                partition=EvaluationPartition.FAMILIAR,
                family_id=FAMILIAR_FAMILY_ID,
                ecology_id=FAMILIAR_ECOLOGY.label,
            ),
            EvaluationWorldTemplate(
                partition=EvaluationPartition.DISTRIBUTION,
                family_id=FAMILIAR_FAMILY_ID,
                ecology_id=DISTRIBUTION_ECOLOGY.label,
            ),
            EvaluationWorldTemplate(
                partition=EvaluationPartition.MECHANISM,
                family_id=MARKOV_REGIME_JUMP_FACTOR_T_V1,
                ecology_id=DISTRIBUTION_ECOLOGY.label,
            ),
        ),
    )


def world_seed(base_seed: int, index: int) -> int:
    """The M10.6 world-seed derivation, preserved exactly."""

    return (base_seed * 1_000_003 + index * 7_919) % 2_147_483_647


def default_world_id(*, index: int, partition: EvaluationPartition) -> str:
    """The M10.6 world identifier: index and partition, never the family."""

    return f"bench-{index:04d}-{partition.value}"


def resolve_world(
    *,
    plan: EvaluationPlan,
    index: int,
    registry: MarketProcessRegistry,
    base_seed: int,
    ecologies: EcologyRegistry | None = None,
    seed: int | None = None,
    world_identifier: str | None = None,
) -> PlannedWorld:
    """Resolve one world of ``plan`` into a concrete, provenance-carrying value.

    Provenance always comes from a plan: there is no plan-less world, so every
    world can be traced back to the campaign and version that declared it.
    ``seed`` and ``world_identifier`` are explicit overrides for callers that need
    a specific world (a replayed campaign, a test); otherwise the M10.6
    derivations apply.
    """

    template = plan.template_for(index)
    ecology_registry = ecologies or default_ecology_registry()
    definition: ProcessFamilyDefinition = registry.resolve(template.family_id)
    split = DatasetSplit.PUBLIC_EVAL if definition.is_public else DatasetSplit.SEALED_EVAL
    return PlannedWorld(
        plan_id=plan.plan_id,
        plan_version=plan.version,
        index=index,
        world_id=world_identifier
        if world_identifier is not None
        else default_world_id(index=index, partition=template.partition),
        seed=world_seed(base_seed, index) if seed is None else seed,
        template=template,
        ecology=ecology_registry.resolve(template.ecology_id),
        family_visibility=definition.visibility,
        public_family_label=definition.public_label,
        family_commitment=registry.commitment(template.family_id),
        split=split,
    )


def plan_worlds(
    *,
    plan: EvaluationPlan,
    registry: MarketProcessRegistry,
    count: int,
    base_seed: int,
    ecologies: EcologyRegistry | None = None,
) -> tuple[PlannedWorld, ...]:
    """Resolve the first ``count`` worlds of ``plan``.

    Every world is resolved before any of them is returned, so an unknown family
    or ecology raises :class:`UnknownProcessFamilyError` (or ``KeyError`` for an
    ecology) instead of producing a half-built campaign.
    """

    if count < 1:
        raise ValueError("a plan needs at least one world")
    return tuple(
        resolve_world(
            plan=plan,
            index=index,
            registry=registry,
            base_seed=base_seed,
            ecologies=ecologies,
        )
        for index in range(count)
    )
