def world_seed(base_seed: int, index: int) -> int:
    """The M10.6 world-seed derivation, preserved exactly."""

    return (base_seed * 1_000_003 + index * 7_919) % 2_147_483_647


def default_world_id(*, index: int, partition: EvaluationPartition) -> str:
    """The M10.6 world identifier: index and partition, never the family."""

    return f"bench-{index:04d}-{partition.value}"


def resolve_world(
    *,
    plan: EvaluationPlan,
    index: int,
    registry: MarketProcessRegistry,
    base_seed: int,
    ecologies: EcologyRegistry | None = None,
    seed: int | None = None,
    world_identifier: str | None = None,
) -> PlannedWorld:
    """Resolve one world of ``plan`` into a concrete, provenance-carrying value.

    Provenance always comes from a plan: there is no plan-less world, so every
    world can be traced back to the campaign and version that declared it.
    ``seed`` and ``world_identifier`` are explicit overrides for callers that need
    a specific world (a replayed campaign, a test); otherwise the M10.6
    derivations apply.
    """

    template = plan.template_for(index)
    ecology_registry = ecologies or default_ecology_registry()
    definition: ProcessFamilyDefinition = registry.resolve(template.family_id)
    # Split provenance re-checked from the visibility matrix on every resolution:
    # an explicitly-seeded or caller-constructed path cannot silently present a
    # split the family visibility contradicts. (Defense in depth; plan-validating
    # callers perform the same check as a whole-plan phase.)
    check_split_matrix(definition=definition, template=template)
    split = template.split
    return PlannedWorld(
        plan_id=plan.plan_id,
        plan_version=plan.version,
        index=index,
        world_id=world_identifier
        if world_identifier is not None
        else default_world_id(index=index, partition=template.resolved_partition),
        seed=world_seed(base_seed, index) if seed is None else seed,
        template=template,
        ecology=ecology_registry.resolve(template.ecology_id),
        family_visibility=definition.visibility,
        public_family_label=definition.public_label,
        family_commitment=registry.commitment(template.family_id),
        split=split,
    )


def validate_plan(
    *,
    plan: EvaluationPlan,
    registry: MarketProcessRegistry,
    ecologies: EcologyRegistry | None = None,
) -> None:
    """Resolve *every* family and ecology ``plan`` names, not just a prefix.

    A plan is a declaration about a whole campaign, so a world count shorter than
    the cycle must not weaken it: with a three-template sealed plan and two
    requested worlds, checking only the prefix would let the private family go
    unverified and the run would silently contain only public worlds.

    Resolving a family also computes its commitment, which builds its nodes for
    every role, so a definition that cannot construct a node fails here rather
    than part-way through a campaign. Neither an unregistered family nor an
    unregistered ecology can therefore be discovered late.

    M10.7 adds the whole-plan split matrix: every template's declared split is
    validated against its family's visibility (never in the reverse order: TRAINABLE
    and PUBLIC_EVAL are *uses* of public families, SEALED_EVAL is reserved for
    evaluator-private ones) and against its partition, so an invalid combination
    fails to build a campaign at all rather than after worlds have been generated.
    """

    ecology_registry = ecologies or default_ecology_registry()
    for template in plan.worlds:
        check_split_matrix(definition=registry.resolve(template.family_id), template=template)
    for family_id in plan.family_ids():
        registry.commitment(family_id)
    for ecology_id in plan.ecology_ids():
        ecology_registry.resolve(ecology_id)


def plan_worlds(
    *,
    plan: EvaluationPlan,
    registry: MarketProcessRegistry,
    count: int,
    base_seed: int,
    ecologies: EcologyRegistry | None = None,
) -> tuple[PlannedWorld, ...]:
    """Resolve the first ``count`` worlds of ``plan``.

    The whole plan is validated first, and every requested world is resolved before
    any of them is returned, so an unknown family or ecology raises
    :class:`UnknownProcessFamilyError` (or ``KeyError`` for an ecology) instead of
    producing a half-built campaign.
    """

    if count < 1:
        raise ValueError("a plan needs at least one world")
    validate_plan(plan=plan, registry=registry, ecologies=ecologies)
    return tuple(
        resolve_world(
            plan=plan,
            index=index,
            registry=registry,
            base_seed=base_seed,
            ecologies=ecologies,
        )
        for index in range(count)
    )
