"""Explicit evaluation plans (M10.6.1).

M10.6 assigned every world to a partition, a process family, and an ecology
inside the runner, through ``world_design(index)``. That made the *benchmark
design policy* a private detail of the runner: an evaluator could not state what a
campaign consisted of, could not reuse it, and could not run a plan on a family
the public repository does not contain.

M10.6.1 makes the plan an explicit, immutable value. A plan is an ordered cycle of
:class:`EvaluationWorldTemplate` entries; world ``i`` uses template ``i % n`` of the
cycle (each template repeated ``weight`` times). Resolving a plan against a
:class:`~app.benchmark.process_registry.MarketProcessRegistry` and an ecology
registry produces concrete :class:`PlannedWorld` values, so every world carries
the provenance an authorized replay needs, including the **split classification**
that keeps sealed evaluation worlds out of any future training corpus.

Resolution happens *before* any world is generated: a plan that names a family the
registry does not hold fails with ``UNKNOWN_PROCESS_FAMILY`` and no partial
campaign is produced.
"""

